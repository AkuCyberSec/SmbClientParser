const SVG_NAMESPACE = "http://www.w3.org/2000/svg";

/** Returns an SVG element for the icon. Icons are decorative: buttons need their own text or aria-label. */
export function icon(name) {
  const svg = document.createElementNS(SVG_NAMESPACE, "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.setAttribute("aria-hidden", "true");
  svg.setAttribute("focusable", "false");
  svg.classList.add("icon");
  // Safe: the content comes from the constants above, never from user data
  svg.innerHTML = ICONS[name] ?? "";
  return svg;
}

/** Replaces every <span data-icon="name"></span> placeholder in the HTML with its icon. */
export function renderIcons(root = document) {
  for (const placeholder of root.querySelectorAll("[data-icon]")) {
    placeholder.replaceWith(icon(placeholder.dataset.icon));
  }
}
